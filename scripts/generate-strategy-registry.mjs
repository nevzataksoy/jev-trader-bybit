import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const rootDirectory = resolve(scriptDirectory, "..");
const modelsDirectory = join(rootDirectory, "lib", "strategy", "models");
const strategyDirectory = join(rootDirectory, "lib", "strategy");

async function directories(path) {
  return (await readdir(path, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

async function filesRecursively(path) {
  const entries = await readdir(path, { withFileTypes: true });
  const output = [];
  for (const entry of entries) {
    const fullPath = join(path, entry.name);
    if (entry.isDirectory()) output.push(...await filesRecursively(fullPath));
    else if (entry.isFile() && entry.name.endsWith(".ts")) output.push(fullPath);
  }
  return output;
}

const families = await directories(modelsDirectory);
const models = [];
for (const family of families) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(family)) {
    throw new Error(`Strategy model family must be kebab-case: ${family}`);
  }
  const familyPath = join(modelsDirectory, family);
  for (const version of await directories(familyPath)) {
    if (!/^v[1-9][0-9]*$/.test(version)) {
      throw new Error(`Strategy model version directory must be v1, v2, ...: ${family}/${version}`);
    }
    const versionPath = join(familyPath, version);
    const entryPath = join(versionPath, "index.ts");
    await readFile(entryPath, "utf8").catch(() => {
      throw new Error(`Strategy model version is missing index.ts: ${family}/${version}`);
    });
    models.push({
      family,
      version,
      id: `${family}-${version}`,
      versionPath,
      importPath: `./models/${family}/${version}`,
    });
  }
}

if (!models.length) {
  throw new Error(`No strategy model versions found in ${relative(rootDirectory, modelsDirectory)}.`);
}

for (const model of models) {
  const ownRoot = resolve(model.versionPath) + sep;
  for (const file of await filesRecursively(model.versionPath)) {
    if (file.endsWith(".test.ts")) continue;
    const source = await readFile(file, "utf8");
    const imports = [...source.matchAll(/(?:from\s+["\']|import\s+["\']|import\s*\(\s*["\'])(\.\.?\/[^"\']+)["\']/g)]
      .map((match) => match[1]);
    for (const specifier of imports) {
      const resolved = resolve(dirname(file), specifier);
      const insideModels = resolved === resolve(modelsDirectory) || resolved.startsWith(resolve(modelsDirectory) + sep);
      const insideOwnVersion = resolved === resolve(model.versionPath) || resolved.startsWith(ownRoot);
      if (insideModels && !insideOwnVersion) {
        throw new Error(
          `Strategy isolation violation in ${relative(rootDirectory, file)}: ${specifier}. `
          + "A model version may import only its own version directory or non-model platform code.",
        );
      }
    }
  }
}

models.sort((a, b) => a.id.localeCompare(b.id));
const catalog = `// Generated by scripts/generate-strategy-registry.mjs. Do not edit.\n`
  + `export const STRATEGY_ENGINE_IDS = ${JSON.stringify(models.map((model) => model.id))} as const;\n`;

const imports = models
  .map((model, index) => `import engine${index + 1} from "${model.importPath}";`)
  .join("\n");
const entries = models
  .map((model, index) => `  ${JSON.stringify(model.id)}: engine${index + 1},`)
  .join("\n");
const registry = `// Generated by scripts/generate-strategy-registry.mjs. Do not edit.\n`
  + `import type { StrategyEngine } from "./types";\n`
  + `${imports}\n\n`
  + `export const strategyEngines = {\n${entries}\n} satisfies Record<string, StrategyEngine>;\n\n`
  + `for (const [id, engine] of Object.entries(strategyEngines)) {\n`
  + `  if (engine.id !== id) throw new Error("Strategy registry id " + id + " does not match exported engine id " + engine.id + ".");\n`
  + `}\n`;

await Promise.all([
  writeFile(join(strategyDirectory, "catalog.generated.ts"), catalog, "utf8"),
  writeFile(join(strategyDirectory, "registry.generated.ts"), registry, "utf8"),
]);

process.stdout.write(`Strategy registry generated for: ${models.map((model) => model.id).join(", ")}\n`);
